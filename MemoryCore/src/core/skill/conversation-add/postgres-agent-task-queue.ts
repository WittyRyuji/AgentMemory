import { randomUUID } from "node:crypto";
import { setTimeout as sleep } from "node:timers/promises";
import { PostgresDatabase } from "../../store/postgres/client.js";
import { PostgresStateBackend } from "../../state/postgres-backend.js";
import {
  serializeAgentTuple,
  parseAgentTuple,
  type AgentTuple,
  type ISkillAgentTaskQueue,
  type ExtractLockHandle,
  type PeekStrategy,
} from "./agent-task-queue.js";

/** At-least-once rotating agent queue; archives/tasks remain in PG object storage. */
export class PostgresSkillAgentTaskQueue implements ISkillAgentTaskQueue {
  private ready?: Promise<void>;
  private readonly locks: PostgresStateBackend;
  constructor(private readonly db: PostgresDatabase) {
    this.locks = new PostgresStateBackend(db);
  }
  private async init() {
    this.ready ??= (async () => {
      await this.locks.initialize();
      await this.db.exec(
        "CREATE TABLE IF NOT EXISTS skill_agents(raw TEXT PRIMARY KEY, instance_id TEXT NOT NULL, queued BOOLEAN NOT NULL DEFAULT TRUE, position BIGINT GENERATED BY DEFAULT AS IDENTITY)",
      );
    })().catch((e) => {
      this.ready = undefined;
      throw e;
    });
    return this.ready;
  }
  async enqueueAgent(tuple: AgentTuple) {
    await this.init();
    return (
      (
        await this.db.query(
          "INSERT INTO skill_agents(raw,instance_id) VALUES($1,$2) ON CONFLICT(raw) DO NOTHING",
          [serializeAgentTuple(tuple), tuple.instance_id],
        )
      ).rowCount === 1
    );
  }
  private async take(
    blockMs: number,
    peek: boolean,
  ): Promise<AgentTuple | null> {
    await this.init();
    const deadline = Date.now() + Math.max(0, blockMs);
    do {
      const rows = (
        await this.db.query<{ raw: string }>(
          `UPDATE skill_agents SET queued=$1,position=nextval(pg_get_serial_sequence('skill_agents','position')) WHERE raw=(SELECT raw FROM skill_agents WHERE queued ORDER BY position LIMIT 1 FOR UPDATE SKIP LOCKED) RETURNING raw`,
          [peek],
        )
      ).rows;
      if (rows.length) return parseAgentTuple(rows[0].raw);
      if (Date.now() >= deadline) return null;
      await sleep(Math.min(100, deadline - Date.now()));
    } while (true);
  }
  dequeueAgent(ms: number) {
    return this.take(ms, false);
  }
  peekAgent(ms: number) {
    return this.take(ms, true);
  }
  getPeekStrategy(): PeekStrategy {
    return "lmove";
  }
  async requeueAgent(tuple: AgentTuple) {
    await this.enqueueAgent(tuple);
    await this.enqueueRawAgent(serializeAgentTuple(tuple));
  }
  async removeAgent(tuple: AgentTuple) {
    await this.purgeRawAgent(serializeAgentTuple(tuple));
  }
  async purgeRawAgent(raw: string) {
    await this.init();
    await this.db.query("DELETE FROM skill_agents WHERE raw=$1", [raw]);
  }
  async scanAgentSet() {
    await this.init();
    return (
      await this.db.query<{ raw: string }>(
        "SELECT raw FROM skill_agents ORDER BY position",
      )
    ).rows.map((r) => r.raw);
  }
  async listContains(raw: string) {
    await this.init();
    return (
      (
        await this.db.query(
          "SELECT 1 FROM skill_agents WHERE raw=$1 AND queued",
          [raw],
        )
      ).rows.length > 0
    );
  }
  async enqueueRawAgent(raw: string) {
    await this.init();
    await this.db.query(
      "UPDATE skill_agents SET queued=true,position=nextval(pg_get_serial_sequence('skill_agents','position')) WHERE raw=$1",
      [raw],
    );
  }
  async withTasksMutex<T>(
    tuple: AgentTuple,
    opts: { lockTtlMs: number; waitDeadlineMs: number },
    fn: () => Promise<T>,
  ): Promise<T> {
    await this.init();
    const key = `skill-tasks:${serializeAgentTuple(tuple)}`,
      token = randomUUID(),
      deadline = Date.now() + opts.waitDeadlineMs;
    while (!(await this.locks.acquireLock(key, token, opts.lockTtlMs))) {
      if (Date.now() >= deadline) throw new Error("Skill tasks mutex timeout");
      await sleep(Math.min(50, Math.max(1, deadline - Date.now())));
    }
    let lost = false,
      renewing = false;
    const timer = setInterval(
      () => {
        if (renewing) return;
        renewing = true;
        void this.locks
          .renewLock(key, token, opts.lockTtlMs)
          .then((ok) => {
            if (!ok) lost = true;
          })
          .catch(() => {
            lost = true;
          })
          .finally(() => {
            renewing = false;
          });
      },
      Math.max(50, Math.floor(opts.lockTtlMs / 3)),
    );
    timer.unref();
    try {
      const result = await fn();
      if (lost) throw new Error("Skill tasks mutex lease lost");
      return result;
    } finally {
      clearInterval(timer);
      await this.locks.releaseLock(key, token);
    }
  }
  async acquireExtractLock(
    tuple: AgentTuple,
    ttl: number,
  ): Promise<ExtractLockHandle | null> {
    await this.init();
    const key = `skill-extract:${serializeAgentTuple(tuple)}`,
      token = randomUUID();
    return (await this.locks.acquireLock(key, token, ttl))
      ? { key, token }
      : null;
  }
  renewExtractLock(handle: ExtractLockHandle, ttl: number) {
    return this.locks.renewLock(handle.key, handle.token, ttl);
  }
  releaseExtractLock(handle: ExtractLockHandle) {
    return this.locks.releaseLock(handle.key, handle.token);
  }
  async purgeInstance(instanceId: string) {
    await this.init();
    const tuples_removed =
      (
        await this.db.query("DELETE FROM skill_agents WHERE instance_id=$1", [
          instanceId,
        ])
      ).rowCount ?? 0;
    let locks_removed = 0;
    for (const prefix of ["skill-tasks:", "skill-extract:"])
      locks_removed +=
        (
          await this.db.query(
            "DELETE FROM pipeline_locks WHERE starts_with(key,$1)",
            [`${prefix}${instanceId}|`],
          )
        ).rowCount ?? 0;
    return { tuples_removed, locks_removed, backend: "postgres" as const };
  }
}
